# Source-folder fallbacks when filename rules do not match.
_SOURCE_HINTS: list[tuple[str, tuple[str, ...]]] = [
    ("Folders", ("folders", "folders 2")),
    ("Drives & Cloud", ("devices/drives", "devices/discs", "emblems/onedrive")),
    ("Devices & Printers", ("devices/printers", "devices/monitors", "devices")),
    ("Symbols & Badges", ("emblems",)),
    ("UI Controls", ("mono",)),
    ("Windows System", ("system",)),
    ("Apps & Utilities", ("applications", "random", "objects")),
]


def _normalize_name(stem: str) -> str:
    return re.sub(r"\s+", " ", stem.strip().lower().replace("_", " "))


def _matches(name: str, pattern: str) -> bool:
    pat = pattern.lower()
    if "*" in pat or "?" in pat:
        return fnmatch(name, pat)
    return name == pat or name.startswith(pat + " ") or name.endswith(" " + pat)


def categorize_icon(stem: str, source_path: str = "") -> str:
    """Return a display category for an icon filename."""
    name = _normalize_name(stem)
    rel = source_path.replace("\\", "/").lower().strip("/")

    for category, patterns in _CATEGORY_RULES:
        for pattern in patterns:
            if _matches(name, pattern):
                return category

    for category, prefixes in _SOURCE_HINTS:
        for prefix in prefixes:
            if rel == prefix or rel.startswith(prefix + "/"):
                return category

    return "Other"


def category_sort_key(category: str) -> tuple[int, str]:
    order = [cat for cat, _ in _CATEGORY_RULES] + ["Other"]
    try:
        return (order.index(category), category.lower())
    except ValueError:
        return (len(order), category.lower())
